const $=id=>document.getElementById(id);
const save=document.createElement('button');
save.id='save-result';save.type='button';save.className='secondary';save.textContent='Download result';save.disabled=true;
document.querySelector('.actions').append(save);
let exportText='';
function clear(){$('result').textContent='';$('diagram').hidden=true;exportText='';save.disabled=true;}
['scale','resize','length','unit'].forEach(k=>$(k).addEventListener('input',clear));
function fmt(n){return Number(n.toFixed(6)).toLocaleString('en-US',{maximumFractionDigits:6});}
$('calculate').addEventListener('click',()=>{
  clear();
  const n=Number($('scale').value),p=Number($('resize').value),l=Number($('length').value),u=$('unit').value;
  if(['scale','resize','length'].some(k=>$(k).value==='')||!Number.isInteger(n)||n<1||n>1e8||!Number.isFinite(p)||p<25||p>200||!Number.isFinite(l)||l<0||l>1000||!['cm','mm','in'].includes(u)){
    $('result').textContent='Use a whole scale denominator from 1 to 100,000,000, print size 25–200%, and a measured length from 0 to 1,000.';
    return;
  }
  const cm=l*({cm:1,mm:.1,in:2.54}[u]),effective=n/(p/100),metres=cm*effective/100,oldMetres=cm*n/100;
  const summary='Effective ratio: approximately 1:'+fmt(effective)+'\nDistance: '+fmt(metres)+' metres ('+fmt(metres/1000)+' km).\nUsing the old ratio on this copy would give '+fmt(oldMetres)+' metres.\nFormula: measured centimetres × original denominator ÷ (print percentage / 100) ÷ 100.\nRounded to six decimal places; inputs and map accuracy limit precision.';
  $('result').textContent=summary+'\nDownload stays on this device; the browser does not send it to PastRush.';
  exportText='Resized map scale calculation\n\nOriginal ratio: 1:'+fmt(n)+'\nUniform print size: '+fmt(p)+'%\nMeasured length: '+fmt(l)+' '+u+' ('+fmt(cm)+' cm)\n\n'+summary+'\n\nAssumptions: uniform resizing, an appropriate local scale, and a map accurate enough for this arithmetic. A straight-line result is not a route or navigation estimate.\nGenerated by the Honest Little Apps browser companion for PastRush.';
  save.disabled=false;
  $('diagram').hidden=false;
  $('copyline').style.width=(40*p/100)+'%';
  $('copylabel').textContent='Copy at '+p+'%: '+fmt(p/100)+' times the original paper length.';
});
save.addEventListener('click',()=>{
  if(save.disabled||!exportText)return;
  const url=URL.createObjectURL(new Blob([exportText+'\n'],{type:'text/plain;charset=utf-8'}));
  const a=document.createElement('a');a.href=url;a.download='resized-map-scale-result.txt';document.body.append(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(url),1500);
});
$('reset').addEventListener('click',()=>{$('scale').value='50000';$('resize').value='150';$('length').value='3';$('unit').value='cm';clear();});
